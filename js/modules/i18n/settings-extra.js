const SETTINGS_EXTRA_DICTIONARY = { en: EN, zh: ZH };

export function st(key, params) {
  const language = getLanguage();
  const value = SETTINGS_EXTRA_DICTIONARY[language]?.[key] ?? EN[key] ?? key;
  if (!params) return value;
  return String(value).replace(/\{(\w+)\}/g, (_, name) => {
    const replacement = params[name];
    return replacement === undefined || replacement === null ? `{${name}}` : String(replacement);
  });
}
